import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { initializeSchema } from './review-store.mjs';
import { ReviewBot, matchesSecret } from './review-bot.mjs';

const db = new DatabaseSync(':memory:');
const sql = { exec(text,...args) {
  const stmt=db.prepare(text);
  if (/^SELECT|RETURNING/i.test(text)) return { toArray: () => stmt.all(...args) };
  stmt.run(...args);
} };
initializeSchema(sql);
const calls=[];
const applicant={ id:3, username:'applicant' }, admin={ id:1 }, privateChat=id=>({type:'private',id});
let count=7;
const api=async (name,args) => {
  calls.push([name,args]);
  if (name==='getChat') return {title:'Test'};
  if (name==='getUserProfilePhotos') return {total_count:1};
  if (name==='getChatMember') return {status: args.user_id === 1 ? 'creator' : 'left'};
  if (name==='sendMessage') return {message_id:calls.length};
  if (name==='createChatInviteLink') return {invite_link:'https://t.me/+test'};
  return true;
};
const bot=new ReviewBot(sql,api,{reviewer_ids:[1],targets:{'-2':'问题'},min_common_groups:8},async()=>({commonGroups:count}));
const call = (action, person) => bot.callback({id:action,data:action,from:person,message:{message_id:12,chat:privateChat(person.id)}});
const sub=(uid,link)=>bot.join({chat:{id:-2},from:{id:uid},invite_link:{invite_link:link}},calls.length);
assert.equal(matchesSecret('testing','valid'),false);
assert.equal(matchesSecret('valid','valid'),true);
await call('apply:-2',applicant);
assert.equal(bot.request(1).state,'rejected');
assert.ok(calls.some(([n,a])=>n==='sendMessage'&&a.chat_id===3&&a.text.includes('共同群不足8个')));
count=8;
await call('apply:-2',applicant);
await bot.message({chat:privateChat(3),from:applicant,text:'审核答案'});
assert.equal(bot.request(2).state,'review');
assert.ok(calls.some(([n,a])=>n==='sendMessage'&&a.chat_id===1&&a.text.includes('审核答案')));
await call('approve:2',admin);
assert.equal(bot.request(2).state,'invited');
const invite=calls.find(([n])=>n==='createChatInviteLink')[1];
assert.equal(invite.creates_join_request,true);
assert.equal('expire_date' in invite,false);
await sub(4,'https://t.me/+test');
assert.equal(bot.request(2).state,'invited');
await sub(3,'https://t.me/+test');
await sub(3,'https://t.me/+test');
assert.equal(bot.request(2).state,'redeemed');
assert.equal(bot.request(2).invite,null);
assert.deepEqual(calls.filter(([n])=>n==='approveChatJoinRequest').map(([,a])=>a.user_id),[3]);
assert.equal(calls.filter(([n])=>n==='revokeChatInviteLink').length,1);
const options = {reviewer_ids:[1],targets:{'-2':'问题'}};
const pinApi=async (method,args)=>{
  calls.push([method,args]);
  if (method==='getMe') return {id:8,username:'test_bot'};
  if (method==='getChat') return {linked_chat_id:-1001234567890};
  if (method==='getChatMember') return {status:'administrator',can_pin_messages:true};
  return true;
};
const pinBot=new ReviewBot(sql,pinApi,options,null,async (_,__,observed)=>{
  assert.deepEqual([...observed.keys()],[21]);
  return [21,22,99];
});
const group={id:-2,type:'supergroup'};
const forward=message_id=>({chat:group,message_id,is_automatic_forward:true,sender_chat:{id:-1001234567890,type:'channel'}});
await pinBot.message(forward(21));
await pinBot.message(forward(22));
await pinBot.message({chat:group,from:{id:1},pinned_message:forward(22)});
await pinBot.message({chat:group,from:{id:1},message_id:40,text:'/unpinall'});
assert.deepEqual(calls.filter(([m])=>m==='unpinChatMessage').map(([,a])=>a.message_id),[21]);
assert.equal(calls.some(([m])=>m==='unpinAllChatMessages'),false);
assert.equal(pinBot.first('SELECT kind FROM pin_provenance WHERE chat=? AND message=?',-2,22).kind,'manual');
db.close();
console.log('Cloud group pin protection passed');
console.log('Staging flow: reject, answer, admin approval, account-bound one-use invite passed');
